const assets={rabbit,hedgehog,elephant,squirrel,panda,ox,fox,dog,lion,wolf,pig,cat,monkey,sheep,tiger,crab,giraffe,horse,rooster,duck,deer};
type Person=GatheringSnapshot['gathering']['owner'];
const legacy:Record<string,keyof typeof assets>={bear:'panda',koala:'hedgehog',penguin:'duck',owl:'rooster',capybara:'squirrel'};
export function GatheringPerson({person}:{person:Person}){
  const parts=gatheringAvatarParts(person.avatar_key);
  const animal=parts?.animal||(person.animal_id&&legacy[person.animal_id])||(person.animal_id&&person.animal_id in assets?person.animal_id as keyof typeof assets:'rabbit');
  return <View className="gg-person"><View className="gg-avatar gg-animal-avatar" style={{backgroundColor:parts?.background||'#D6DFC8'}}><Image className="gg-animal-portrait" src={assets[animal]} mode="aspectFill"/></View><Text className="gg-person-name">{person.nickname}</Text></View>;
}
